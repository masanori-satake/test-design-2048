import pytest
from src.game_manager import is_game_over

@pytest.mark.parametrize("test_id, rule, board, expected", [
    ("TC-S2-01", "R1", [
        [2, 2, 4, 8],
        [2, 16, 32, 64],
        [4, 8, 16, 32],
        [8, 16, 32, 0]
    ], False), # 空きマスあり・水平可・垂直可
    ("TC-S2-02", "R2", [
        [2, 2, 4, 8],
        [16, 32, 64, 128],
        [256, 512, 1024, 2048],
        [4096, 8192, 16384, 0]
    ], False), # 空きマスあり・水平可・垂直不可
    ("TC-S2-03", "R3", [
        [2, 4, 8, 16],
        [2, 32, 64, 128],
        [256, 512, 1024, 2048],
        [4096, 8192, 16384, 0]
    ], False), # 空きマスあり・水平不可・垂直可
    ("TC-S2-04", "R4", [
        [2, 4, 8, 16],
        [32, 64, 128, 256],
        [512, 1024, 2048, 4096],
        [8192, 16384, 32768, 0]
    ], False), # 空きマスあり・水平不可・垂直不可
    ("TC-S2-05", "R5", [
        [2, 2, 4, 8],
        [2, 16, 32, 64],
        [4, 8, 16, 32],
        [8, 16, 32, 64]
    ], False), # 空きマス0・水平可・垂直可
    ("TC-S2-06", "R6", [
        [2, 2, 4, 8],
        [16, 32, 64, 128],
        [256, 512, 1024, 2048],
        [4096, 8192, 16384, 32768]
    ], False), # 空きマス0・水平可・垂直不可
    ("TC-S2-07", "R7", [
        [2, 4, 8, 16],
        [2, 32, 64, 128],
        [256, 512, 1024, 2048],
        [4096, 8192, 16384, 32768]
    ], False), # 空きマス0・水平不可・垂直可
    ("TC-S2-08", "R8", [
        [2, 4, 2, 4],
        [4, 2, 4, 2],
        [2, 4, 2, 4],
        [4, 2, 4, 2]
    ], True), # 空きマス0・水平不可・垂直不可 (ゲームオーバー)
])
def test_is_game_over(test_id, rule, board, expected):
    """
    TC-S2-01〜08: デシジョンテーブル（R1〜R8）を網羅するテスト。
    """
    assert is_game_over(board) is expected

